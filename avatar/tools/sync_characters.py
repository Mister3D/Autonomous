#!/usr/bin/env python3
"""Rebuild avatar/vue/catalog.js from ready characters in avatar/characters/."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHARS = ROOT / "characters"
PENDING = ROOT / "pending"
VUE = ROOT / "vue"


def main() -> None:
    VUE.mkdir(exist_ok=True)
    catalog: dict = {}
    for meta_path in sorted(CHARS.glob("*/meta.json")):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        aid = meta["id"]
        svg_path = meta_path.parent / f"{aid}.svg"
        vc_path = meta_path.parent / f"{aid}.vectorcraft"
        pending_vc = PENDING / f"{aid}.vectorcraft"
        has_vc = vc_path.exists() or pending_vc.exists()
        if meta.get("hasVectorcraft") != has_vc:
            meta["hasVectorcraft"] = has_vc
            meta_path.write_text(
                json.dumps(meta, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
        ready = bool(meta.get("ready"))
        print(f"{aid}: ready={ready} vc={has_vc}")
        if not ready:
            continue
        if not svg_path.exists():
            raise SystemExit(f"missing SVG for ready character: {svg_path}")
        svg_text = svg_path.read_text(encoding="utf-8")
        catalog[aid] = {
            "id": aid,
            "title": meta.get("title") or aid,
            "defaultColor": meta.get("defaultColor", 0),
            "rig": meta.get("rig"),
            "svg": svg_text,
        }
    out = (
        "/* Auto-generated by avatar/tools/sync_characters.py — do not edit by hand. */\n"
        "export const CATALOG = "
        + json.dumps(catalog, ensure_ascii=False)
        + ";\nexport const CHARACTER_IDS = "
        + json.dumps(sorted(catalog.keys()))
        + ";\nexport function getCharacter(id) {\n  return CATALOG[id] || null;\n}\n"
    )
    (VUE / "catalog.js").write_text(out, encoding="utf-8")
    print("catalog", sorted(catalog.keys()))


if __name__ == "__main__":
    main()
